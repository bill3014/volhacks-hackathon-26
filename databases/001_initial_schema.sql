begin;

-- =========================================
-- 1. CAMPUS SPACES
-- =========================================

create table public.spaces (
                               id bigint generated by default as identity primary key,

                               name text not null
                                   check (length(trim(name)) > 0),

                               category text not null
                                   check (category in ('Library', 'Study room', 'Dining hall')),

                               location text not null,

                               capacity integer not null
                                   check (capacity > 0),

                               amenities text[] not null default '{}',

                               background text not null default '#e4e8dc'
                                   check (background ~ '^#[0-9A-Fa-f]{6}$'),

  artwork text not null default 'library'
    check (artwork in ('library', 'room', 'dining')),

  -- NULL means no report has been received.
  occupied integer,

  occupancy_updated_at timestamptz,

  occupancy_source text
    check (
      occupancy_source in ('student_report', 'staff', 'sensor')
    ),

  -- How long a report remains useful.
  stale_after_minutes integer not null default 30
    check (stale_after_minutes > 0),

  created_at timestamptz not null default now(),

  constraint valid_occupancy
    check (
      occupied is null
      or occupied between 0 and capacity
    ),

  constraint consistent_occupancy_metadata
    check (
      (
        occupied is null
        and occupancy_updated_at is null
        and occupancy_source is null
      )
      or
      (
        occupied is not null
        and occupancy_updated_at is not null
        and occupancy_source is not null
      )
    )
);


-- =========================================
-- 2. OCCUPANCY REPORT HISTORY
-- =========================================

create table public.occupancy_reports (
                                          id bigint generated always as identity primary key,

                                          space_id bigint not null
                                              references public.spaces(id) on delete cascade,

                                          reporter_id uuid
                                                          references auth.users(id) on delete set null,

                                          occupied integer not null
                                              check (occupied >= 0),

                                          source text not null
                                              check (source in ('student_report', 'staff', 'sensor')),

                                          reported_at timestamptz not null default now()
);

create index occupancy_reports_space_time_idx
    on public.occupancy_reports (
                                 space_id,
                                 reported_at desc,
                                 id desc
        );

create index occupancy_reports_reporter_idx
    on public.occupancy_reports (reporter_id);


-- =========================================
-- 3. USER FAVORITES
-- =========================================

create table public.favorites (
                                  user_id uuid not null
                                      references auth.users(id) on delete cascade,

                                  space_id bigint not null
                                      references public.spaces(id) on delete cascade,

                                  created_at timestamptz not null default now(),

                                  primary key (user_id, space_id)
);

create index favorites_space_idx
    on public.favorites (space_id);


-- =========================================
-- 4. ACCESS POLICIES
-- =========================================

alter table public.spaces enable row level security;

alter table public.occupancy_reports
    enable row level security;

alter table public.favorites enable row level security;


-- Anyone can view space information.
create policy "Anyone can read spaces"
  on public.spaces
  for select
                 to anon, authenticated
                 using (true);


-- Users can read their own report history.
create policy "Users can read their own reports"
  on public.occupancy_reports
  for select
                 to authenticated
                 using ((select auth.uid()) = reporter_id);


-- Favorites belong to the signed-in user.
create policy "Users can read their own favorites"
  on public.favorites
  for select
                 to authenticated
                 using ((select auth.uid()) = user_id);

create policy "Users can add their own favorites"
  on public.favorites
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can delete their own favorites"
  on public.favorites
  for delete
to authenticated
  using ((select auth.uid()) = user_id);


-- Explicitly limit browser access.
revoke all on public.spaces
    from anon, authenticated;

revoke all on public.occupancy_reports
    from anon, authenticated;

revoke all on public.favorites
    from anon, authenticated;

grant select on public.spaces
    to anon, authenticated;

grant select on public.occupancy_reports
    to authenticated;

grant select, insert, delete on public.favorites
    to authenticated;


-- =========================================
-- 5. SUBMIT AN OCCUPANCY REPORT
-- =========================================
-- The browser calls this function.
-- Both the history and current count update
-- together in one transaction.

create function public.submit_occupancy_report(
    p_space_id bigint,
    p_occupied integer
)
    returns bigint
    language plpgsql
security definer
set search_path = ''
as $$
declare
v_user_id uuid;
  v_capacity integer;
  v_report_id bigint;
  v_reported_at timestamptz;
begin
  v_user_id := auth.uid();

  if v_user_id is null then
    raise exception 'Sign in before submitting a report.';
end if;

  -- Lock this space so simultaneous submissions
  -- update its current count in a consistent order.
select capacity
into v_capacity
from public.spaces
where id = p_space_id
    for update;

if not found then
    raise exception 'Space not found.';
end if;

  if p_occupied is null
     or p_occupied < 0
     or p_occupied > v_capacity then
    raise exception
      'Occupancy must be between 0 and %.',
      v_capacity;
end if;

  -- Use the database time, not a browser-supplied time.
  v_reported_at := clock_timestamp();

insert into public.occupancy_reports (
    space_id,
    reporter_id,
    occupied,
    source,
    reported_at
)
values (
           p_space_id,
           v_user_id,
           p_occupied,
           'student_report',
           v_reported_at
       )
    returning id into v_report_id;

update public.spaces
set occupied = p_occupied,
    occupancy_updated_at = v_reported_at,
    occupancy_source = 'student_report'
where id = p_space_id;

return v_report_id;
end;
$$;

revoke all on function public.submit_occupancy_report(
    bigint,
    integer
    ) from public, anon, authenticated;

grant execute on function public.submit_occupancy_report(
  bigint,
  integer
) to authenticated;


-- =========================================
-- 6. FRONTEND OCCUPANCY VIEW
-- =========================================
-- Stale reports remain in history, but their
-- counts are not presented as current availability.

create view public.space_status
            with (security_invoker = true)
as
    with freshness as (
    select
    s.*,

    (
    s.occupied is not null
    and s.occupancy_updated_at >
    now() - make_interval(mins => s.stale_after_minutes)
) as is_fresh

    from public.spaces s
)
select
    id,
    name,
    category,
    location,
    capacity,
    amenities,
    background,
    artwork,

    occupied as last_reported_occupied,
    occupancy_updated_at,
    occupancy_source,
    stale_after_minutes,
    is_fresh,

    case
        when is_fresh then occupied
        else null
        end as occupied,

    case
        when is_fresh then capacity - occupied
        else null
        end as available_seats,

    case
        when is_fresh then
            round(100.0 * occupied / capacity)::integer
    else null
end as occupancy_percentage,

  case
    when occupied is null then 'No reports'
    when not is_fresh then 'Stale'
    when occupied = capacity then 'Full'
    when occupied::numeric / capacity >= 0.80 then 'Busy'
    when occupied::numeric / capacity >= 0.50 then 'Filling up'
    else 'Available'
end as status

from freshness;

grant select on public.space_status
    to anon, authenticated;


